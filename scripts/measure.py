#!/usr/bin/env python3
"""Size measurements for the paper: this extension vs. SaneQL's own implementation vs. DuckDB's SQL front end.

Usage: scripts/measure.py [path-to-upstream-saneql-clone] > MEASUREMENTS.md

Line counts are physical lines unless marked "code", which excludes blank lines and lines that are only a
comment. DuckDB numbers come from the pinned submodule; SaneQL numbers from a clone of github.com/neumannt/saneql.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DUCKDB = ROOT / "duckdb"
UPSTREAM = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/saneql_upstream")


def lines(path):
    return path.read_text(errors="replace").splitlines()


def code_lines(path, comment=("//", "#")):
    return sum(1 for l in lines(path) if l.strip() and not l.strip().startswith(comment))


def total(paths, fn=lambda p: len(lines(p))):
    return sum(fn(p) for p in paths)


def git_rev(path):
    try:
        return subprocess.check_output(["git", "-C", str(path), "describe", "--tags", "--always"], text=True).strip()
    except Exception:
        return "unknown"


out = []
p = out.append


def query_rows():
    rows = []
    for i in range(1, 23):
        n = f"{i:02d}"
        sane = [l.strip() for l in lines(ROOT / f"examples/tpch/q{n}.sane") if l.strip()]
        sql = [l.strip() for l in lines(DUCKDB / f"extension/tpch/dbgen/queries/q{n}.sql") if l.strip()]
        sane_text = "\n".join(sane)
        lets = len(re.findall(r"^let\b", sane_text, re.M))
        ops = len(re.findall(r"\.(filter|join|groupby|aggregate|orderby|project|map|as)\(", sane_text))
        rows.append((n, [len(sane), len(sql), sum(map(len, sane)), sum(map(len, sql)), lets, ops]))
    return rows


gram_files = sorted((DUCKDB / "src/parser/peg/grammar/statements").glob("*.gram"))
keyword_files = sorted((DUCKDB / "src/parser/peg/grammar/keywords").glob("*.list"))
transformer_files = sorted((DUCKDB / "src/parser/peg/transformer").glob("*.cpp"))
generated = [f for f in transformer_files if "generated" in f.name]
handwritten = [f for f in transformer_files if "generated" not in f.name]
infra = sorted((DUCKDB / "src/parser/peg").glob("*.cpp")) + sorted((DUCKDB / "src/parser/peg/tokenizer").glob("*.cpp"))
binder = sorted((DUCKDB / "src/planner/binder").rglob("*.cpp"))


QUERY_ROWS = query_rows()
sums_total = [sum(r[1][k] for r in QUERY_ROWS) for k in range(6)]

# --- this extension -------------------------------------------------------------------------------------------
grammar = ROOT / "src/include/saneql_grammar.hpp"
rules = [l for l in lines(grammar) if re.match(r"^[A-Za-z]+ <-", l)]
sql_rule_names = set()
for gram in (DUCKDB / "src/parser/peg/grammar/statements").glob("*.gram"):
    sql_rule_names.update(m.group(1) for l in lines(gram) if (m := re.match(r"^([A-Za-z]+)(\([A-Z]\))? <-", l)))
replaced = [r for r in rules if r.split(" ")[0] in sql_rule_names]
transformer = ROOT / "src/saneql_transformer.cpp"
sections = {}
current = "includes"
transformer_lines = lines(transformer)
for i, l in enumerate(transformer_lines):
    if l.startswith("// ") and i > 0 and transformer_lines[i - 1].startswith("//==="):
        current = l[3:].strip()
    if l.strip() and not l.strip().startswith("//"):
        sections[current] = sections.get(current, 0) + 1
ext_cpp = [transformer, ROOT / "src/saneql_extension.cpp", ROOT / "src/include/saneql_dialect.hpp",
           ROOT / "src/include/saneql_extension.hpp"]
tests = sorted((ROOT / "test/sql").rglob("*.test"))

p("# Measurements\n")
p(f"Generated by `scripts/measure.py`. DuckDB submodule at {git_rev(DUCKDB)}; upstream SaneQL at "
  f"{git_rev(UPSTREAM)} ({UPSTREAM}).\n")
p("## Headline\n")
p(f"- The dialect is {len(rules)} grammar rules and {total(ext_cpp, code_lines)} lines of C++ (code lines), "
  "on top of DuckDB's SQL grammar, transformer and binder.")
if UPSTREAM.exists():
    sem = total(list(UPSTREAM.glob("semana/*.cpp")) + list(UPSTREAM.glob("semana/*.hpp")), code_lines)
    gram = code_lines(UPSTREAM / "parser/saneql.ypp")
    lex = total(list(UPSTREAM.glob("parser/SaneQLLexer.*")), code_lines)
    p(f"- SaneQL's own translator spends {gram} code lines on its bison grammar and {lex} on its lexer, but "
      f"{sem} on semantic analysis plus {total(list(UPSTREAM.glob('algebra/*')), code_lines)} on its algebra: "
      "the semantic layer is the bulk there too. Here that layer is DuckDB's binder, shared with SQL.")
sql_gram = total(gram_files, code_lines)
sql_tf = total(handwritten, code_lines) + total(generated, code_lines)
p(f"- DuckDB's SQL grammar is {len(sql_rule_names)} rules ({sql_gram} code lines) with "
  f"{sql_tf} code lines of transformer. The SaneQL dialect adds {len(rules) * 100 / len(sql_rule_names):.1f}% "
  f"to the rule count and {code_lines(transformer) * 100 / sql_tf:.1f}% to the transformer, and reuses the rest.")
p(f"- Across the 22 TPC-H queries, SaneQL text is {sums_total[0]} lines against {sums_total[1]} for SQL "
  f"({sums_total[2]} vs. {sums_total[3]} characters): the two languages say the same thing in about the same "
  "number of characters, formatted differently.")
p("")
p("## The SaneQL dialect extension\n")
p("| Part | Lines | Code lines |")
p("|---|---:|---:|")
p(f"| Grammar rules ({len(rules)} rules: {len(rules) - len(replaced)} added, {len(replaced)} replace SQL rules) "
  f"| {len(rules)} | {len(rules)} |")
p(f"| `saneql_transformer.cpp` (tree walk, SELECT builder, let/method rewriter, grammar splice) "
  f"| {len(lines(transformer))} | {code_lines(transformer)} |")
p(f"| Extension entry and headers | {total(ext_cpp[1:])} | {total(ext_cpp[1:], code_lines)} |")
p(f"| **All C++** | **{total(ext_cpp)}** | **{total(ext_cpp, code_lines)}** |")
p(f"| Tests ({len(tests)} sqllogictest files) | {total(tests)} | |")
p("")
p("Transformer code lines by section:\n")
p("| Section | Code lines |")
p("|---|---:|")
for name, n in sections.items():
    p(f"| {name} | {n} |")
p("")

# --- upstream SaneQL ------------------------------------------------------------------------------------------
if UPSTREAM.exists():
    def group(globs):
        files = [f for g in globs for f in UPSTREAM.glob(g)]
        return total(files), total(files, code_lines), sum(f.stat().st_size for f in files) // 1024

    p("## SaneQL's own implementation (SaneQL to SQL translator)\n")
    p("| Part | Lines | Code lines | KB |")
    p("|---|---:|---:|---:|")
    for label, globs in [
        ("Grammar (`parser/saneql.ypp`, bison)", ["parser/saneql.ypp"]),
        ("Lexer (`parser/SaneQLLexer.*`)", ["parser/SaneQLLexer.cpp", "parser/SaneQLLexer.hpp"]),
        ("AST (`parser/ASTBase.*`, `Keywords.hpp`, `SaneQLParser.hpp`) + AST generator (`makeutil/astgen.cpp`)",
         ["parser/ASTBase.*", "parser/Keywords.hpp", "parser/SaneQLParser.hpp", "makeutil/astgen.cpp"]),
        ("Semantic analysis (`semana/*`)", ["semana/*.cpp", "semana/*.hpp"]),
        ("Algebra (`algebra/*`)", ["algebra/*.cpp", "algebra/*.hpp"]),
        ("SQL writer (`sql/*`)", ["sql/*.cpp", "sql/*.hpp"]),
        ("Schema, main (`infra/*`, `main.cpp`)", ["infra/*", "main.cpp"]),
        ("**Total**", ["parser/*", "makeutil/*", "semana/*", "algebra/*", "sql/*", "infra/*", "main.cpp"]),
    ]:
        n, c, kb = group(globs)
        p(f"| {label} | {n} | {c} | {kb} |")
    p("")

# --- DuckDB -----------------------------------------------------------------------------------------------------
p("## DuckDB's SQL front end (pinned submodule)\n")
p("| Part | Lines | Code lines |")
p("|---|---:|---:|")
p(f"| PEG grammar (`src/parser/peg/grammar/statements/*.gram`, {len(sql_rule_names)} rules) "
  f"| {total(gram_files)} | {total(gram_files, code_lines)} |")
p(f"| Keyword lists (`grammar/keywords/*.list`) | {total(keyword_files)} | {total(keyword_files, code_lines)} |")
p(f"| Transformer, hand-written (`src/parser/peg/transformer/*.cpp` minus generated) "
  f"| {total(handwritten)} | {total(handwritten, code_lines)} |")
p(f"| Transformer, generated trampolines | {total(generated)} | {total(generated, code_lines)} |")
p(f"| Parser infrastructure (`src/parser/peg/*.cpp`, tokenizer; matchers, packrat, dialects, formatter) "
  f"| {total(infra)} | {total(infra, code_lines)} |")
p(f"| Binder (`src/planner/binder/**/*.cpp`, shared by every dialect) | {total(binder)} | {total(binder, code_lines)} |")
p("")

# --- per query --------------------------------------------------------------------------------------------------
p("## TPC-H queries: SaneQL vs. SQL text\n")
p("SaneQL from `examples/tpch/` (upstream examples; q5 corrected), SQL from DuckDB's tpch extension "
  "(`extension/tpch/dbgen/queries/`). Lines are non-blank lines; characters exclude leading/trailing whitespace per line.\n")
p("| Query | SaneQL lines | SQL lines | SaneQL chars | SQL chars | SaneQL `let`s | SaneQL operators |")
p("|---|---:|---:|---:|---:|---:|---:|")
for n, row in QUERY_ROWS:
    p(f"| q{n} | " + " | ".join(str(v) for v in row) + " |")
sums = sums_total
p("| **Total** | " + " | ".join(f"**{v}**" for v in sums) + " |")
p("")
print("\n".join(out))
